    private static Block register(ResourceKey<Block> id, Function<BlockBehaviour.Properties, Block> factory, BlockBehaviour.Properties properties) {
        Block block = factory.apply(properties.setId(id));

        return Registry.register(BuiltInRegistries.BLOCK, id, block);
    }

    private static Block register(BlockItemId id, Function<BlockBehaviour.Properties, Block> factory, BlockBehaviour.Properties properties, boolean fireproofItem) {
        Block block = register(id.block(), factory, properties);

        BlockItem blockItem;

        if (fireproofItem) {
            blockItem = new BlockItem(block, new Item.Properties().useBlockDescriptionPrefix().setId(id.item()).fireResistant());
        } else {
            blockItem = new BlockItem(block, new Item.Properties().useBlockDescriptionPrefix().setId(id.item()));
        }

        Registry.register(BuiltInRegistries.ITEM, id.item(), blockItem);

        return block;
    }

    private static final BlockBehaviour.StateArgumentPredicate<AABB> NEAR_PLANE_INTERSECTS_OUTLINE = (state, level, blockPos, nearPlaneBox) -> {
        for(AABB outlineBox : state.getOcclusionShape().toAabbs()) {
            if (outlineBox.move(blockPos).intersects(nearPlaneBox)) {
                return true;
            }
        }

        return false;
    };

    private static Block registerStair(final BlockItemId id, final Block base, boolean fireproofItem) {
        return register(id, (p) -> new StairBlock(base.defaultBlockState(), p), BlockBehaviour.Properties.ofFullCopy(base).isViewBlocking(NEAR_PLANE_INTERSECTS_OUTLINE), fireproofItem);
    }

    private static Block registerSlab(final BlockItemId id, final Block base, boolean fireproofItem) {
        return register(id, SlabBlock::new, BlockBehaviour.Properties.ofFullCopy(base).isViewBlocking(NEAR_PLANE_INTERSECTS_OUTLINE), fireproofItem);
    }

    private static Block registerWall(final BlockItemId id, final Block base, boolean fireproofItem) {
        return register(id, WallBlock::new, BlockBehaviour.Properties.ofFullCopy(base).forceSolidOn(), fireproofItem);
    }

